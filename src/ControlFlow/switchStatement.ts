//...Switch Statement 
let day : number = 5;

switch(day){
case 1 :
    console.log("MONDAY");
    break;
case 2 :
    console.log("TUESDAY");
    break;
case 3 :
    console.log("Wednesday");
    break;
case 4 :
    console.log("Thursday");
    break;
case 5 :
   console.log("FRIDAY");
   break;
default :
   console.log("..WEEKEND..");
   break;   
}   
